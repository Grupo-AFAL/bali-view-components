export function translator (overrides) {
  const table = { ...DEFAULT_I18N, ...(overrides || {}) }
  const t = (key, vars) => interpolate(String(table[key] ?? key), vars)
  t.words = (key) => String(table[key] || '').split('|').map((w) => w.trim().toLowerCase()).filter(Boolean)
  t.has = (key) => table[key] != null
  t.count = (base, count) => t(count === 1 ? `${base}_one` : `${base}_other`, { count })
  return t
}
