# #708 — references to entities embedded in BlockNote content. `record` is the one that
# CONTAINS the reference (a document, a task, whatever the host marks with
# Bali::EntityReferenceable) and `referenceable` is the one referred to. Both polymorphic:
# the engine knows neither class.
#
# NO foreign key on `referenceable` ON PURPOSE: a reference to a deleted record must
# survive to be drawn as a broken chip (`broken: true`), which is exactly what the JS expects.
# An FK with ON DELETE would silently delete it and the reader would lose the signal.
class CreateBaliEntityReferences < ActiveRecord::Migration[7.0]
  def change
    create_table :bali_entity_references do |t|
      # The `references` default indexes would be redundant: the unique one below covers the
      # [record_type, record_id] prefix and the lookup one covers [referenceable_type, referenceable_id].
      t.references :record, polymorphic: true, null: false, index: false
      t.references :referenceable, polymorphic: true, null: false, index: false
      # The referred record's name AT THE TIME it was written: it lets references be listed
      # without resolving each type, and it is all that remains when the referred record disappears.
      t.string :reference_text

      t.timestamps
    end

    # Short name: the autogenerated one with four columns overruns PG's identifier limit.
    add_index :bali_entity_references,
              %i[record_type record_id referenceable_type referenceable_id],
              unique: true, name: "index_bali_entity_references_uniqueness"

    # The inverse (`incoming_references`): who references this record.
    add_index :bali_entity_references, %i[referenceable_type referenceable_id],
              name: "index_bali_entity_references_on_referenceable"
  end
end
