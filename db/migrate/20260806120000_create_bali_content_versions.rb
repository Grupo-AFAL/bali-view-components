# #707 — content history for the document engine. The table is GENERIC on purpose:
# a polymorphic `record`, so a document, a policy or a note share history without Bali
# knowing any of those models (`Bali.content_versionables` decides which are exposed over
# HTTP).
#
# `author` is polymorphic and OPTIONAL, `author_name` is required and denormalized:
# the JSON that `document_editor/index.js` consumes serves `author_name` (contract frozen
# in the v3.0 betas), and the author pair enables "my versions"/auditing without a future migration.
# A host with no user model, or with string ids like the BlockEditor comments,
# leaves `author` nil and keeps working.
class CreateBaliContentVersions < ActiveRecord::Migration[7.0]
  def change
    create_table :bali_content_versions do |t|
      # The unique index below covers the [record_type, record_id] prefix; the references
      # default index would be redundant.
      t.references :record, polymorphic: true, null: false, index: false
      # jsonb only exists on Postgres; the engine's dummy (and any sqlite host) uses json.
      if connection.adapter_name.match?(/postg/i)
        t.jsonb :content
        t.jsonb :metadata, null: false, default: {}
      else
        t.json :content
        t.json :metadata, null: false, default: {}
      end
      t.integer :version_number, null: false
      t.references :author, polymorphic: true, null: true, index: false
      t.string :author_name, null: false
      # A summary is one line. The limit is the belt to the model's suspenders
      # (`Bali::ContentVersion::SUMMARY_MAX_LENGTH`): without it, `summary` is unbounded
      # text coming from a host form.
      t.string :summary, limit: 255

      t.timestamps
    end

    # The audit that the comment above promises ("my versions") filters by the author
    # pair, and without this index it would be a full scan of the whole table.
    add_index :bali_content_versions, %i[author_type author_id],
              name: "index_bali_content_versions_on_author"

    # Short name: the autogenerated one with these three columns overruns the
    # PG identifier limit.
    add_index :bali_content_versions, %i[record_type record_id version_number],
              unique: true, name: "index_bali_content_versions_uniqueness"
  end
end
